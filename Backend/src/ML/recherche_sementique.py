import pandas as pd

dataImobilie = pd.read_csv("src/ML/imobilieData.csv")
dataImobilie.head()

dataImobilie.columns

dataImobilie["texte"] = (
    "Type: " + dataImobilie["proprety type"].astype(str) +
    ", Prix: " + dataImobilie["price_£"].astype(str) +
    ", Surface: " + dataImobilie["surface"].astype(str) +
    ", Chambres: " + dataImobilie["bathroom"].astype(str) +
    ", Salles de bain: " + dataImobilie["bedroom"].astype(str) +
    ", Adresse: " + dataImobilie["address"].astype(str) +
    ", Ville: " +dataImobilie["city"].astype(str) +
    ", Région: " + dataImobilie["principale"].astype(str)
)

dataImobilie.head()

from sentence_transformers import SentenceTransformer

# fait une transformer --> Embeding system :
Model_Transformer = SentenceTransformer("all-MiniLM-L6-v2")
embeddings = Model_Transformer.encode(
    dataImobilie['texte'].tolist(),
    batch_size=64,
    show_progress_bar=True  # affiche une barre de progression
)

dataImobilie['embedding'] = list(embeddings)



dataImobilie.head()

#Test sur request user
requete = "Appartement à Fes, 2 chambres, 120 m², proche du centre"

requete_emb = Model_Transformer.encode([requete])

from sklearn.metrics.pairwise import cosine_similarity
import numpy as np

# Calculer la similarité entre la requête et toutes les annonces
similarites = cosine_similarity(requete_emb, list(dataImobilie['embedding']))[0]

# Ajouter les scores dans le dataframe
dataImobilie['score'] = similarites

# Trier les résultats par score décroissant
resultats = dataImobilie.sort_values('score', ascending=False)
resultats.head()

dataImobilie['id'] = dataImobilie.index.astype(str)

# Data Retourner var user l'orsque fait search simentique

# creation d'une database vectorielle pour fait une Recherche vectorilelle



from chromadb import Client
from chromadb.config import  Settings

# Création du client Chroma DB
client = Client(Settings(
    persist_directory="./chroma_data"
))

# Créer une collection
collection = client.create_collection("imobilie_00")

# Ajouter les embeddings et métadonnées
batch_size = 5000  # inférieur à la limite
for i in range(0, len(dataImobilie), batch_size):
    batch = dataImobilie.iloc[i:i+batch_size]
    collection.add(
        ids=batch['id'].tolist(),
        embeddings=batch['embedding'].tolist(),
        metadatas=batch[['price_£','proprety type','surface','bedroom','bathroom','address','city','principale']].to_dict(orient="records"),
        documents=batch['texte'].tolist()
    )


